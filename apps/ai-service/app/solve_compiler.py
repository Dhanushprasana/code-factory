from __future__ import annotations

import base64
import json
from pathlib import Path
from typing import Any

from app.patch_engine import is_safe_relative_path


def detect_build_command(repository_path: str) -> str | None:
    """Detect the appropriate build or typecheck command from the checked-out repository."""
    root = Path(repository_path)
    package_json = root / "package.json"
    if package_json.is_file():
        try:
            data = json.loads(package_json.read_text(encoding="utf-8"))
            scripts = data.get("scripts") or {}
            if isinstance(scripts.get("build"), str):
                return "npm run build"
            if isinstance(scripts.get("typecheck"), str):
                return "npm run typecheck"
            if (root / "tsconfig.json").is_file():
                return "npx tsc --noEmit"
        except (OSError, json.JSONDecodeError):
            pass

    if (root / "pyproject.toml").is_file() or (root / "requirements.txt").is_file():
        return "python3 -m compileall -q ."
    if (root / "go.mod").is_file():
        return "go build ./..."
    if (root / "Cargo.toml").is_file():
        return "cargo check"
    return None


def _b64(text: str) -> str:
    return base64.b64encode(text.encode("utf-8")).decode("ascii")


def compile_solve_script(
    modifications: list[dict[str, Any]],
    repositories: list[dict[str, Any]],
) -> str:
    """
    Deterministically compile validated modifications into an executable solve.sh script.
    Base64 encoding is always produced here—never by the LLM—to avoid shell quoting bugs.
    """
    lines: list[str] = [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        "",
        "# Auto-generated by TaskForge deterministic solve.sh compiler",
        "PYTHON_BIN=\"$(command -v python3 || command -v python)\"",
        "",
        "apply_replace() {",
        "  local file_path=\"$1\"",
        "  local search_b64=\"$2\"",
        "  local replace_b64=\"$3\"",
        "  \"$PYTHON_BIN\" - \"$file_path\" \"$search_b64\" \"$replace_b64\" <<'PYEOF'",
        "import base64, pathlib, sys",
        "path = pathlib.Path(sys.argv[1])",
        "if not path.is_file():",
        "    sys.stderr.write(f'Missing target file: {path}\\n')",
        "    sys.exit(1)",
        "content = path.read_bytes().decode('utf-8')",
        "search = base64.b64decode(sys.argv[2]).decode('utf-8')",
        "replace = base64.b64decode(sys.argv[3]).decode('utf-8')",
        "count = content.count(search)",
        "if count != 1:",
        "    sys.stderr.write(f'Expected 1 match in {path}, found {count}\\n')",
        "    sys.exit(1)",
        "idx = content.index(search)",
        "updated = content[:idx] + replace + content[idx + len(search):]",
        "path.write_bytes(updated.encode('utf-8'))",
        "PYEOF",
        "}",
        "",
        "apply_insert() {",
        "  local file_path=\"$1\"",
        "  local anchor_b64=\"$2\"",
        "  local insert_b64=\"$3\"",
        "  local position=\"$4\"",
        "  \"$PYTHON_BIN\" - \"$file_path\" \"$anchor_b64\" \"$insert_b64\" \"$position\" <<'PYEOF'",
        "import base64, pathlib, sys",
        "path = pathlib.Path(sys.argv[1])",
        "if not path.is_file():",
        "    sys.stderr.write(f'Missing target file: {path}\\n')",
        "    sys.exit(1)",
        "content = path.read_bytes().decode('utf-8')",
        "anchor = base64.b64decode(sys.argv[2]).decode('utf-8')",
        "inserted = base64.b64decode(sys.argv[3]).decode('utf-8')",
        "position = sys.argv[4]",
        "count = content.count(anchor)",
        "if count != 1:",
        "    sys.stderr.write(f'Expected 1 anchor match in {path}, found {count}\\n')",
        "    sys.exit(1)",
        "idx = content.index(anchor)",
        "if position == 'before':",
        "    updated = content[:idx] + inserted + content[idx:]",
        "else:",
        "    end = idx + len(anchor)",
        "    updated = content[:end] + inserted + content[end:]",
        "path.write_bytes(updated.encode('utf-8'))",
        "PYEOF",
        "}",
        "",
        "apply_create() {",
        "  local file_path=\"$1\"",
        "  local content_b64=\"$2\"",
        "  \"$PYTHON_BIN\" - \"$file_path\" \"$content_b64\" <<'PYEOF'",
        "import base64, pathlib, sys",
        "path = pathlib.Path(sys.argv[1])",
        "if path.exists():",
        "    sys.stderr.write(f'Refusing to overwrite existing file: {path}\\n')",
        "    sys.exit(1)",
        "path.parent.mkdir(parents=True, exist_ok=True)",
        "path.write_bytes(base64.b64decode(sys.argv[2]))",
        "PYEOF",
        "}",
        "",
        "apply_delete() {",
        "  local file_path=\"$1\"",
        "  if [ ! -f \"$file_path\" ]; then",
        "    echo \"Missing file to delete: $file_path\" >&2",
        "    exit 1",
        "  fi",
        "  rm -- \"$file_path\"",
        "}",
        "",
    ]

    for idx, mod in enumerate(modifications, start=1):
        file_path = str(mod["file_path"])
        if not is_safe_relative_path(file_path):
            raise ValueError(f"Unsafe relative path in modification {idx}: {file_path}")
        operation = mod["operation"]
        description = str(mod.get("description", "")).replace("\n", " ").strip()
        lines.append(f"# Step {idx}: {operation} {file_path} - {description}")
        if operation == "replace":
            lines.append(
                f"apply_replace '{file_path}' '{_b64(mod['search'])}' '{_b64(mod['replace'])}'"
            )
        elif operation == "insert":
            position = mod.get("position", "after")
            lines.append(
                f"apply_insert '{file_path}' '{_b64(mod['search'])}' '{_b64(mod['replace'])}' '{position}'"
            )
        elif operation == "create":
            lines.append(f"apply_create '{file_path}' '{_b64(mod['replace'])}'")
        elif operation == "delete":
            lines.append(f"apply_delete '{file_path}'")
        else:
            raise ValueError(f"Unsupported operation: {operation}")
        lines.append("")

    build_commands: list[str] = []
    for repo in repositories:
        repo_path = repo.get("repository_path")
        if isinstance(repo_path, str):
            cmd = detect_build_command(repo_path)
            if cmd and cmd not in build_commands:
                build_commands.append(cmd)

    if build_commands:
        lines.append("# Repository verification build/typecheck")
        lines.extend(build_commands)
        lines.append("")

    return "\n".join(lines)
